import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";

import {
  ProductionsLayout,
  RehearsalSessionsLayout,
  SessionCastCallsLayout,
} from "../config/schemas/filemaker/client";
import { emptyOnNoRecords } from "../lib/data";
import { RecordEditModal } from "./record-edit-modal";
import type { DevFieldGroup } from "./record-edit-modal";

const SESSION_TYPE_OPTIONS = [
  "Rehearsal",
  "Tech",
  "Dress",
  "Sitzprobe",
  "Performance",
];

const SESSION_TYPE_COLORS: Record<string, string> = {
  Dress: "bg-orange-100 text-orange-700",
  Performance: "bg-gold-200 text-navy-700",
  Rehearsal: "bg-green-200 text-green-800",
  Sitzprobe: "bg-navy-100 text-navy-600",
  Tech: "bg-navy-100 text-navy-600",
};

const FIELD_GROUPS: DevFieldGroup[] = [
  {
    fields: [
      {
        key: "idProduction",
        kind: "text",
        label: "Show (idProduction)",
        span2: true,
      },
      {
        key: "SessionType",
        kind: "select",
        label: "Session type",
        options: SESSION_TYPE_OPTIONS,
      },
      { key: "DateSession", kind: "date", label: "Date" },
      { key: "TimeStart", kind: "time", label: "Start time" },
      { key: "TimeEnd", kind: "time", label: "End time" },
      { key: "Location", kind: "text", label: "Location", span2: true },
      {
        key: "PerformanceLabel",
        kind: "text",
        label: "Performance label (e.g. Opening night)",
        span2: true,
      },
      {
        key: "isAutoGenerated",
        kind: "select",
        label: "Auto-generated by scheduler (0/1)",
        options: ["0", "1"],
      },
    ],
  },
  {
    fields: [{ key: "Notes", kind: "textarea", label: "Notes", span2: true }],
  },
];

const fmtDate = (d: string) => {
  if (!d) {
    return "—";
  }
  const dt = new Date(d);
  if (Number.isNaN(dt.getTime())) {
    return d;
  }
  return dt.toLocaleDateString("en-US", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
};

const fmtTime = (t: string) => {
  if (!t) {
    return "—";
  }
  const [h, m] = t.split(":");
  const hourNum = Number(h);
  if (Number.isNaN(hourNum) || m === undefined) {
    return t;
  }
  const period = hourNum >= 12 ? "PM" : "AM";
  const hour12 = ((hourNum + 11) % 12) + 1;
  return `${hour12}:${m} ${period}`;
};

export const RehearsalsTab = () => {
  const queryClient = useQueryClient();
  const [search, setSearch] = useState("");
  const [selectedRecordId, setSelectedRecordId] = useState<string | null>(null);

  // Sequential — see ScenesTab for why (single-threaded FM script execution
  // behind the WebViewerAdapter; concurrent fmFetch calls queue and stall).
  const { data, isLoading, isError, error } = useQuery({
    queryFn: async () => {
      const sessions = await emptyOnNoRecords(() =>
        RehearsalSessionsLayout.list({
          sort: [
            { fieldName: "DateSession", sortOrder: "ascend" },
            { fieldName: "TimeStart", sortOrder: "ascend" },
          ],
        })
      );
      const productions = await emptyOnNoRecords(() =>
        ProductionsLayout.list()
      );
      const calls = await emptyOnNoRecords(() => SessionCastCallsLayout.list());
      return {
        calls: calls.data,
        productions: productions.data,
        sessions: sessions.data,
      };
    },
    queryKey: ["dev-rehearsals-bundle"],
  });

  const sessions = data?.sessions ?? [];
  const productionsById = new Map(
    (data?.productions ?? []).map((p) => [p.fieldData.id, p.fieldData.Title])
  );

  const callStatsBySession = new Map<
    string,
    { total: number; conflicts: number }
  >();
  for (const c of data?.calls ?? []) {
    const key = c.fieldData.idSession;
    const stat = callStatsBySession.get(key) ?? { conflicts: 0, total: 0 };
    stat.total += 1;
    if (c.fieldData.ConflictReason) {
      stat.conflicts += 1;
    }
    callStatsBySession.set(key, stat);
  }

  const q = search.toLowerCase();
  const filtered = sessions.filter((s) => {
    const show = productionsById.get(s.fieldData.idProduction) ?? "";
    return (
      !q ||
      [
        show,
        s.fieldData.SessionType,
        s.fieldData.Location,
        s.fieldData.PerformanceLabel,
      ]
        .join(" ")
        .toLowerCase()
        .includes(q)
    );
  });

  const selected = sessions.find((s) => s.recordId === selectedRecordId);

  const updateMutation = useMutation({
    mutationFn: ({
      recordId,
      fieldData,
    }: {
      recordId: string;
      fieldData: Record<string, string>;
    }) => RehearsalSessionsLayout.update({ fieldData, recordId }),
    onSuccess: () =>
      queryClient.invalidateQueries({ queryKey: ["dev-rehearsals-bundle"] }),
  });

  const deleteMutation = useMutation({
    mutationFn: (recordId: string) =>
      RehearsalSessionsLayout.delete({ recordId }),
    onSuccess: () =>
      queryClient.invalidateQueries({ queryKey: ["dev-rehearsals-bundle"] }),
  });

  return (
    <section>
      <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
        <input
          type="text"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          placeholder="Search by show, session type, location, or label…"
          className="w-full max-w-sm rounded-xl border border-border bg-card px-3.5 py-2 text-base md:text-sm focus:outline-none focus:ring-2 focus:ring-primary/40"
        />
        <span className="text-sm text-muted-foreground">
          {filtered.length} of {sessions.length} records
        </span>
      </div>

      {isLoading && (
        <p className="py-16 text-center text-sm text-muted-foreground">
          Loading rehearsals…
        </p>
      )}
      {isError && (
        <p className="rounded-2xl border border-destructive/30 bg-destructive/5 p-5 text-sm text-destructive">
          Failed to load RehearsalSessions:{" "}
          {error instanceof Error ? error.message : "unknown error"}
        </p>
      )}

      {!isLoading && !isError && (
        <div className="overflow-x-auto rounded-2xl border border-border bg-card">
          <table className="w-full min-w-[640px] text-sm">
            <thead>
              <tr className="bg-muted text-left text-xs font-semibold uppercase tracking-wide text-muted-foreground">
                <th className="px-4 py-3">Date</th>
                <th className="px-4 py-3">Session type</th>
                <th className="px-4 py-3">Show</th>
                <th className="px-4 py-3">Time</th>
                <th className="px-4 py-3">Location</th>
                <th className="px-4 py-3">Calls</th>
                <th className="px-4 py-3">id</th>
              </tr>
            </thead>
            <tbody>
              {filtered.map((s) => {
                const f = s.fieldData;
                const typeClass =
                  SESSION_TYPE_COLORS[f.SessionType] ??
                  "bg-secondary text-muted-foreground";
                const stats = callStatsBySession.get(f.id);
                return (
                  <tr
                    key={s.recordId}
                    onClick={() => setSelectedRecordId(s.recordId)}
                    className="cursor-pointer border-t border-border hover:bg-gold-100 transition-colors"
                  >
                    <td className="px-4 py-3 font-semibold">
                      {fmtDate(f.DateSession)}
                      {f.PerformanceLabel && (
                        <span className="ml-2 text-xs font-normal text-muted-foreground">
                          {f.PerformanceLabel}
                        </span>
                      )}
                    </td>
                    <td className="px-4 py-3">
                      <span
                        className={`rounded-full px-2.5 py-0.5 text-xs font-medium ${typeClass}`}
                      >
                        {f.SessionType || "—"}
                      </span>
                    </td>
                    <td className="px-4 py-3 text-muted-foreground">
                      {productionsById.get(f.idProduction) || "Unknown show"}
                    </td>
                    <td className="px-4 py-3 text-muted-foreground">
                      {fmtTime(f.TimeStart)} – {fmtTime(f.TimeEnd)}
                    </td>
                    <td className="px-4 py-3 text-muted-foreground">
                      {f.Location || "—"}
                    </td>
                    <td className="px-4 py-3 text-muted-foreground">
                      {stats
                        ? `${stats.total} called${
                            stats.conflicts
                              ? ` · ${stats.conflicts} conflict${stats.conflicts === 1 ? "" : "s"}`
                              : ""
                          }`
                        : "0 calls"}
                    </td>
                    <td className="px-4 py-3">
                      <span className="rounded bg-secondary px-1.5 py-0.5 font-mono text-xs text-muted-foreground">
                        {f.id}
                      </span>
                    </td>
                  </tr>
                );
              })}
              {filtered.length === 0 && (
                <tr>
                  <td
                    colSpan={7}
                    className="px-4 py-12 text-center text-sm text-muted-foreground"
                  >
                    No rehearsals match your search.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      )}

      {selected && (
        <RecordEditModal
          eyebrow="Rehearsal · RehearsalSessions"
          title={`${selected.fieldData.SessionType || "Session"} — ${
            productionsById.get(selected.fieldData.idProduction) ||
            "Unknown show"
          }`}
          recordId={selected.recordId}
          fieldData={selected.fieldData}
          groups={FIELD_GROUPS}
          onClose={() => setSelectedRecordId(null)}
          onSave={(fieldData) =>
            updateMutation.mutateAsync({
              fieldData,
              recordId: selected.recordId,
            })
          }
          onDelete={() => deleteMutation.mutateAsync(selected.recordId)}
        />
      )}
    </section>
  );
};
